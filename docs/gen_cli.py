"""Write docs/cli.md from the `rang-core` help texts (task D1).

    python docs/gen_cli.py          # rewrite docs/cli.md
    python docs/gen_cli.py --check  # exit 1 if docs/cli.md is out of date

Every help text comes from running the command line in a subprocess with a
fixed width and no colour, so the page shows exactly what a user sees;
`tests/test_d1_docs.py` runs the check.
"""

import os
import subprocess
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
PAGE = DOCS / "cli.md"

INTRO = """\
# Command line

`rang-core` (also `python -m rang.core_cli`) is one command line for every
archived chain: `rang-core STAGE VERB ARGS...` ({gh}`research/p9-cli.md`).
Each stage has `run` (the driver), `compare` (one comparator engine: the
verdict and counts against an archive) and `archive` (a versioned
`rang.archive` file); `rang-core check` runs the full local checks on any
platform. Every call writes a receipt, `<output>.<verb>.rang-receipt.json`
(schema `rang.receipt` version 2: the command, its inputs, the environment
and the commit), unless `--no-receipt` is given. The OpenBLAS, OpenMP, MKL
and XLA thread pools are capped at one thread where their variables are
unset, unless `--no-pin-threads` is given or `RANG_PIN_THREADS=0` is set;
`RAYON_NUM_THREADS` sets the core's own threads.

The core-native Stimela2 recipes `recipes/core-*.yaml` call the same
functions. Most stages replay a frozen campaign and need its archived inputs
under `outputs/`; the stage help and the linked reports say which.

This page is generated by `docs/gen_cli.py` from the help texts below and
checked against them by the test suite.
"""


def _help(*args):
    env = {
        **os.environ,
        "COLUMNS": "80",
        "NO_COLOR": "1",
        "PYTHON_COLORS": "0",
        "TERM": "dumb",
        "PYTHONUTF8": "1",
    }
    done = subprocess.run(
        [sys.executable, "-m", "rang.core_cli", *args, "-h"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=env,
        check=True,
    )
    return done.stdout.rstrip()


def _block(title, command, text):
    return f"## {title}\n\n```text\n$ {command}\n{text}\n```\n"


def page():
    from rang.core_cli import STAGES

    parts = [INTRO, _block("Overview", "rang-core -h", _help())]
    for stage, entry in STAGES.items():
        parts.append(_block(f"`{stage}`", f"rang-core {stage} -h", _help(stage)))
        for verb, spec in entry.items():
            if verb != "help" and spec["kind"] == "function":
                text = _help(stage, verb)
                parts.append(f"```text\n$ rang-core {stage} {verb} -h\n{text}\n```\n")
    for command in ("check", "environment"):
        parts.append(_block(f"`{command}`", f"rang-core {command} -h", _help(command)))
    return "\n".join(parts)


def main(argv):
    text = page()
    if "--check" in argv:
        if PAGE.read_text(encoding="utf-8") != text:
            print("docs/cli.md is out of date: run python docs/gen_cli.py")
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
