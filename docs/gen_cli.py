"""Write docs/cli.md from the `rang-core` help texts (task D1).

    python docs/gen_cli.py          # rewrite docs/cli.md
    python docs/gen_cli.py --check  # exit 1 if docs/cli.md is out of date

Every help text comes from running the command line in a subprocess with a
fixed width and no colour, so the page shows exactly what a user sees;
`tests/test_d1_docs.py` runs the check.
"""

import os
import subprocess
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
PAGE = DOCS / "cli.md"

INTRO = """\
# Command line

`rang-core` (also `python -m rang.core_cli`) has two parts.

**Your own Measurement Set** ({gh}`research/w2-commands.md`):
`rang-core flag | calibrate | apply | image | selfcal | run CONFIG MS`. One
YAML configuration (schema `rang-config`, version 1; every key and default
is listed under `config` below) drives every stage. The commands validate
the whole configuration first and refuse what is not implemented yet
(`rang-core config check --all CONFIG` lists it). Today `flag` runs the Tricolour port and
writes FLAG, `calibrate` writes calibrator models (setjy, manual, lsm) to
MODEL_DATA and either solves the `complex` term into a QuartiCal gain store
or runs CARACal's K, G, B, A and F terms in order into CASA tables, its A
steps flagging the corrected calibrators ({gh}`research/c2e-calibrate.md`),
then the polcal section's Gpol, KCROSS, Xf and Df
({gh}`research/c6w-polwire.md`), `apply` applies those solutions to
CORRECTED_DATA, with the parallactic angle when `apply.parang` is set, and `image` runs
`gemclean`; `selfcal` runs CARACal's self-calibration rounds (image, model
into MODEL_DATA, an Sp, Sa or Sd solve, apply; {gh}`research/c5-selfcal.md`).
State and outputs go into a run directory (default `<ms>.rang-run`):
`rang-core run` skips finished stages and resumes at a failed one. Before
the first write to an MS its flags are saved as the CASA flag version
`rang_original`, and before each stage writes flags as
`rang_<stage>_<UTC time>` (the MODEL_DATA that image and selfcal write
leaves FLAG alone and saves none).
The Stimela2 recipe `recipes/rang-chain.yaml` runs `flag`, `calibrate`,
`apply` and `image` in order, each as the command above
(`stimela run recipes/rang-chain.yaml config=config.yaml ms=my.ms`; the cabs
are in `recipes/rang-cabs.yaml`, {gh}`research/w5-stimela.md`). The tutorial
{doc}`tutorials/notebooks/00-ms-to-image` runs `rang-core run` and `gemclean`
on a simulated MS and explains each section of the configuration and each
output ({gh}`examples/ms-to-image/config.yaml`).

**The research chains:** `rang-core research STAGE VERB ARGS...`
({gh}`research/p9-cli.md`). Each stage has `run` (the driver), `compare`
(one comparator engine: the verdict and counts against an archive) and
`archive` (a versioned `rang.archive` file). Most stages replay a frozen
campaign and need its archived inputs under `outputs/`; the stage help and
the linked reports say which. The research recipes `recipes/core-*.yaml`
(Stimela2, each marked `# rang-recipe: research`) call the same functions;
they replay frozen campaigns and are not recipes for your own MS.

**CASA's tasks** ({gh}`research/v8-open-casa.md`): `rang-core listobs MS`
summarises a Measurement Set as CASA's `listobs` does, read-only, as text or
`--json` ({gh}`research/v8a-listobs.md`); `rang.tasks.listobs(vis=...)` is
the same in Python under CASA's keyword names. {doc}`casa-users` maps CASA's
tasks to rang's.

`rang-core check` runs the full local checks on any platform. Every call
writes a receipt (schema `rang.receipt` version 5: the command, its inputs,
the environment with every recorded `RANG_*` variable, and the commit, null
outside a source checkout; a Measurement Set it modified is recorded by a
hash of its file sizes and mtimes; the stage summaries hash the flags, gain
solutions and images written, and name the tables and settings behind a
written column), unless `--no-receipt` is given: a research
stage beside its output as `<output>.<verb>.rang-receipt.json`, a command
on a Measurement Set in `<run>/receipts/`. The OpenBLAS, OpenMP, MKL and
XLA thread pools are capped at one thread where their variables are unset,
unless `--no-pin-threads` is given or `RANG_PIN_THREADS=0` is set;
`RAYON_NUM_THREADS` sets the core's own threads.

`gemclean`, the imager the `image` stage runs, is its own command with
WSClean-style options; its usage is at the end of this page
({gh}`research/gemclean.md`, {gh}`research/g8-wheel.md`).

This page is generated by `docs/gen_cli.py` from the help texts below and
checked against them by the test suite.
"""


def _help(*args):
    return _run(*args, "-h")


def _run(*args):
    env = {
        **os.environ,
        "COLUMNS": "80",
        "NO_COLOR": "1",
        "PYTHON_COLORS": "0",
        "TERM": "dumb",
        "PYTHONUTF8": "1",
    }
    done = subprocess.run(
        [sys.executable, "-m", "rang.core_cli", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=env,
        check=True,
    )
    return done.stdout.rstrip()


def _gemclean_help():
    """`gemclean -h`: the usage on stderr, exit 2, as the binary."""
    done = subprocess.run(
        [sys.executable, "-m", "rang.gemclean", "-h"],
        check=False,
        capture_output=True,
        text=True,
        encoding="utf-8",
        env={**os.environ, "NO_COLOR": "1", "PYTHONUTF8": "1"},
    )
    if done.returncode != 2 or "usage: gemclean" not in done.stderr:
        raise SystemExit(f"gemclean -h: exit {done.returncode}: {done.stderr}")
    return done.stderr.rstrip()


def _block(title, command, text):
    return f"## {title}\n\n```text\n$ {command}\n{text}\n```\n"


def page():
    from rang.core_cli import STAGES, USER_COMMANDS

    parts = [INTRO, _block("Overview", "rang-core -h", _help())]
    for command in USER_COMMANDS:
        parts.append(_block(f"`{command}`", f"rang-core {command} -h", _help(command)))
    parts.append(_block("`config`", "rang-core config -h", _help("config")))
    parts.append(
        "The configuration, every key at its default:\n\n"
        f"```text\n$ rang-core config defaults\n{_run('config', 'defaults')}\n```\n"
    )
    # E5-29: the subcommands a user runs before a stage.
    parts.append(
        f"```text\n$ rang-core config check -h\n{_help('config', 'check')}\n```\n"
    )
    parts.append(_block("`formats`", "rang-core formats -h", _help("formats")))
    for verb in ("check", "convert"):
        parts.append(
            f"```text\n$ rang-core formats {verb} -h\n{_help('formats', verb)}\n```\n"
        )
    parts.append(_block("`listobs`", "rang-core listobs -h", _help("listobs")))
    parts.append(_block("`flagdata`", "rang-core flagdata -h", _help("flagdata")))
    parts.append(_block("`research`", "rang-core research -h", _help("research")))
    for stage, entry in STAGES.items():
        parts.append(
            _block(
                f"`research {stage}`",
                f"rang-core research {stage} -h",
                _help("research", stage),
            )
        )
        for verb, spec in entry.items():
            if verb != "help" and spec["kind"] == "function":
                text = _help("research", stage, verb)
                parts.append(
                    f"```text\n$ rang-core research {stage} {verb} -h\n{text}\n```\n"
                )
    parts.append(
        _block(
            "`research environment`",
            "rang-core research environment -h",
            _help("research", "environment"),
        )
    )
    parts.append(_block("`check`", "rang-core check -h", _help("check")))
    parts.append(_block("`gemclean`", "gemclean -h", _gemclean_help()))
    parts.append(environment_section())
    return "\n".join(parts)


def environment_section():
    """The `RANG_*` variables, from the one registry `rang.core.ENVIRONMENT`
    that the receipts record too (task W4-1, research/w4-1-receipts.md)."""
    from rang.core import KINDS, environment_markdown

    kinds = "\n".join(f"- **{kind}**: {text}" for kind, text in KINDS.items())
    return (
        "## Environment variables\n\n"
        "Every `RANG_*` variable that the package or the Rust core reads. "
        "Each receipt records the current value of every variable of the "
        "kinds result, input, speed, output, process and refused, null when "
        "unset (`environment.rang_environment`); the campaign receipts "
        "record the same under `rang_environment`. Kinds:\n\n"
        f"{kinds}\n\n{environment_markdown()}"
    )


def main(argv):
    text = page()
    if "--check" in argv:
        if PAGE.read_text(encoding="utf-8") != text:
            print("docs/cli.md is out of date: run python docs/gen_cli.py")
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
