"""Write docs/cli.md from the `rang-core` help texts (task D1).

    python docs/gen_cli.py          # rewrite docs/cli.md
    python docs/gen_cli.py --check  # exit 1 if docs/cli.md is out of date

Every help text comes from running the command line in a subprocess with a
fixed width and no colour, so the page shows exactly what a user sees;
`tests/test_d1_docs.py` runs the check.
"""

import os
import subprocess
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
PAGE = DOCS / "cli.md"

INTRO = """\
# Command line

`rang-core` (also `python -m rang.core_cli`) has two parts.

**Your own Measurement Set** ({gh}`research/w2-commands.md`):
`rang-core flag | calibrate | apply | image | selfcal | run CONFIG MS`. One
YAML configuration (schema `rang-config`, version 1; every key and default
is listed under `config` below) drives every stage. The commands validate
the whole configuration first and refuse what is not implemented yet,
naming the task that adds it. Today `flag` runs the Tricolour port and
writes FLAG, `calibrate` solves the `complex` term and writes a QuartiCal
gain store, `image` runs `gemclean`, and `apply` and `selfcal` are refused.
State and outputs go into a run directory (default `<ms>.rang-run`):
`rang-core run` skips finished stages and resumes at a failed one. Before
the first write to an MS its flags are saved as the CASA flag version
`rang_original`, and before each stage writes as `rang_<stage>_<UTC time>`.

**The research chains:** `rang-core research STAGE VERB ARGS...`
({gh}`research/p9-cli.md`). Each stage has `run` (the driver), `compare`
(one comparator engine: the verdict and counts against an archive) and
`archive` (a versioned `rang.archive` file). Most stages replay a frozen
campaign and need its archived inputs under `outputs/`; the stage help and
the linked reports say which. The core-native Stimela2 recipes
`recipes/core-*.yaml` call the same functions.

`rang-core check` runs the full local checks on any platform. Every call
writes a receipt (schema `rang.receipt` version 4: the command, its inputs,
the environment with every recorded `RANG_*` variable, and the commit, null
outside a source checkout), unless `--no-receipt` is given: a research
stage beside its output as `<output>.<verb>.rang-receipt.json`, a command
on a Measurement Set in `<run>/receipts/`. The OpenBLAS, OpenMP, MKL and
XLA thread pools are capped at one thread where their variables are unset,
unless `--no-pin-threads` is given or `RANG_PIN_THREADS=0` is set;
`RAYON_NUM_THREADS` sets the core's own threads.

This page is generated by `docs/gen_cli.py` from the help texts below and
checked against them by the test suite.
"""


def _help(*args):
    return _run(*args, "-h")


def _run(*args):
    env = {
        **os.environ,
        "COLUMNS": "80",
        "NO_COLOR": "1",
        "PYTHON_COLORS": "0",
        "TERM": "dumb",
        "PYTHONUTF8": "1",
    }
    done = subprocess.run(
        [sys.executable, "-m", "rang.core_cli", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        env=env,
        check=True,
    )
    return done.stdout.rstrip()


def _block(title, command, text):
    return f"## {title}\n\n```text\n$ {command}\n{text}\n```\n"


def page():
    from rang.core_cli import STAGES, USER_COMMANDS

    parts = [INTRO, _block("Overview", "rang-core -h", _help())]
    for command in USER_COMMANDS:
        parts.append(_block(f"`{command}`", f"rang-core {command} -h", _help(command)))
    parts.append(_block("`config`", "rang-core config -h", _help("config")))
    parts.append(
        "The configuration, every key at its default:\n\n"
        f"```text\n$ rang-core config defaults\n{_run('config', 'defaults')}\n```\n"
    )
    parts.append(_block("`research`", "rang-core research -h", _help("research")))
    for stage, entry in STAGES.items():
        parts.append(
            _block(
                f"`research {stage}`",
                f"rang-core research {stage} -h",
                _help("research", stage),
            )
        )
        for verb, spec in entry.items():
            if verb != "help" and spec["kind"] == "function":
                text = _help("research", stage, verb)
                parts.append(
                    f"```text\n$ rang-core research {stage} {verb} -h\n{text}\n```\n"
                )
    parts.append(
        _block(
            "`research environment`",
            "rang-core research environment -h",
            _help("research", "environment"),
        )
    )
    parts.append(_block("`check`", "rang-core check -h", _help("check")))
    parts.append(environment_section())
    return "\n".join(parts)


def environment_section():
    """The `RANG_*` variables, from the one registry `rang.core.ENVIRONMENT`
    that the receipts record too (task W4-1, research/w4-1-receipts.md)."""
    from rang.core import KINDS, environment_markdown

    kinds = "\n".join(f"- **{kind}**: {text}" for kind, text in KINDS.items())
    return (
        "## Environment variables\n\n"
        "Every `RANG_*` variable that the package or the Rust core reads. "
        "Each receipt records the current value of every variable of the "
        "kinds result, input, speed, output, process and refused, null when "
        "unset (`environment.rang_environment`); the campaign receipts "
        "record the same under `rang_environment`. Kinds:\n\n"
        f"{kinds}\n\n{environment_markdown()}"
    )


def main(argv):
    text = page()
    if "--check" in argv:
        if PAGE.read_text(encoding="utf-8") != text:
            print("docs/cli.md is out of date: run python docs/gen_cli.py")
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
