def write(path, payload):
    Path(path).write_text(json.dumps(payload, indent=1, default=float) + "\n")


def generate(case, out, noiseless=False):
    """The case's MS in `out` (made once); returns its path."""
    name = case + ("-twin" if noiseless else "")
    ms = Path(out) / f"{name}.ms"
    if not ms.exists():
        argv = [sys.executable, str(HERE / "c5_selfcal_sim.py"), case, str(out)]
        subprocess.run(argv + (["--noiseless"] if noiseless else []), check=True)
    return ms


def columns(ms, names, rows=None):
    with core_ms.open_table(ms) as t:
        if rows is None:
            return {n: t.getcol(n) for n in names}
        return {n: t.getcol(n)[rows] for n in names}


def truth_of(ms):
    return np.load(str(ms).removesuffix(".ms") + ".truth.npz")


def bin_blocks(sol_time_bin, row_time, truth):
    """The truth block of each solution bin (None when a bin spans two)."""
    tindex = np.searchsorted(truth["time"], row_time)
    blocks = truth["block"][tindex]
    out = []
    for b in range(int(sol_time_bin.max()) + 1):
        values = np.unique(blocks[sol_time_bin == b])
        out.append(int(values[0]) if len(values) == 1 else None)
    return out


def truth_gains(truth, blocks, nfreq_bins, freq_bin):
    """Truth (bin, freq bin, antenna, hand) for blocks per bin."""
    g = truth["gains"][blocks]  # (bin, chan, ant, 2)
    if nfreq_bins == g.shape[1]:
        return g
    first = [int(np.flatnonzero(freq_bin == f)[0]) for f in range(nfreq_bins)]
    return g[:, first]


def prod_stats(g, flags, gt):
    """Phase (deg) and amplitude-ratio errors of products against truth."""
    p, ok, _ = cal_gain.baseline_products(g, flags)
    pt, _, _ = cal_gain.baseline_products(gt, np.zeros(gt.shape, bool))
    ratio = p[ok] / pt[ok]
    phase = np.degrees(np.abs(np.angle(ratio)))
    amp = np.abs(np.abs(ratio) - 1)
    raw = np.abs(np.abs(pt[ok]) - 1)

    def q(x):
        return {
            "median": float(np.median(x)),
            "p95": float(np.percentile(x, 95)),
            "max": float(x.max()),
        }

    return {
        "products": int(ok.sum()),
        "phase_deg": q(phase),
        "amp_rel": q(amp),
        "uncorrected_amp_rel": q(raw),
        "rel": q(np.abs(ratio - 1)),
    }


def delay_stats(delays, flags, tau):
    """|Δ(τ_p − τ_q)| per hand against truth, ns."""
    nant = delays.shape[-2]
    p, q = np.triu_indices(nant, 1)
    d = delays[:, 0][:, p] - delays[:, 0][:, q]
    t = tau[:, p] - tau[:, q]
    ok = ~flags[:, 0][:, p] & ~flags[:, 0][:, q]
    x = np.abs(d - t)[ok]
    return {
        "pairs": int(ok.sum()),
        "median": float(np.median(x)),
        "p95": float(np.percentile(x, 95)),
        "max": float(x.max()),
    }


def library_solve(ms, term, model_column="MODEL_TRUE"):
    c = columns(ms, ["FIELD_ID"])
    rows = np.flatnonzero(c["FIELD_ID"] == 3)
    return cal_selfcal.solve(
        ms, {"name": term["type"], **term}, rows=rows, field_id=3,
        input_column="DATA", model_column=model_column,
        weight_column="WEIGHT_SPECTRUM", refant=0, gain_clip=(0.5, 2.0),
    )  # fmt: skip


def against_truth(ms, sol):
    truth = truth_of(ms)
    t = columns(ms, ["TIME"], sol.rows)["TIME"]
    blocks = bin_blocks(sol.time_bin, t, truth)
    if any(b is None for b in blocks):
        return None
    gt = truth_gains(truth, blocks, sol.gains.shape[1], sol.freq_bin)
    out = {"products": prod_stats(sol.gains, sol.flags, gt)}
    if sol.delays is not None:
        out["delays"] = delay_stats(sol.delays, sol.flags, truth["tau_ns"][blocks])
    return out


# --- T0 -------------------------------------------------------------------------


def t0(run):
    run = Path(run)
    started = time.perf_counter()
    res, ok = {}, True
    for case, terms in (("c5pa", ("Sa", "Sp")), ("c5delay", ("Sd",))):
        ms = generate(case, run / case, noiseless=True)
        for kind in terms:
            sol = library_solve(ms, {"type": kind, "solint": 8})
            got = against_truth(ms, sol)
            p = got["products"]
            if kind == "Sa":
                passed = p["rel"]["max"] <= T0["Sa"]
            elif kind == "Sp":
                passed = np.radians(p["phase_deg"]["max"]) <= T0["Sp"]
            else:
                passed = (
                    got["delays"]["max"] <= T0["Sd_delay_ns"]
                    and p["rel"]["max"] <= T0["Sd_products"]
                )
            entry = {"truth": got, "pass": bool(passed), "iterations": sol.iterations}
            if kind != "Sp":
                entry["apply"] = t0_apply(ms, sol)
                passed &= entry["apply"]["pass"]
                entry["pass"] = bool(passed)
            res[f"{case}-{kind}"] = entry
            ok &= bool(passed)
    res["wall_s"] = time.perf_counter() - started
    res["pass"] = bool(ok)
    write(run / "t0.json", res)
    return ok


def t0_apply(ms, sol):
    """The applied twin against MODEL_TRUE (relative to |M| on cells with
    |M| above 1 % of its maximum)."""
    from rang import core_writeback

    with core_writeback.WriteBack(ms, stage="c5-t0") as w:
        cal_selfcal.apply(w, sol, input_column="DATA", output_column="CORRECTED_DATA")
    c = columns(ms, ["CORRECTED_DATA", "MODEL_TRUE", "FLAG"], sol.rows)
    m = c["MODEL_TRUE"][..., (0, 3)]
    o = c["CORRECTED_DATA"][..., (0, 3)]
    flagged = c["FLAG"][..., (0, 3)]
    keep = (np.abs(m) > 0.01 * np.abs(m).max()) & ~flagged
    rel = (np.abs(o - m) / np.abs(m))[keep]
    out = {
        "median": float(np.median(rel)),
        "max": float(rel.max()),
        "flagged_fraction": float(flagged.mean()),
    }
    out["pass"] = bool(
        out["median"] <= T0_APPLY["median"] and out["max"] <= T0_APPLY["max"]
    )
    return out


# --- T1 -------------------------------------------------------------------------


def t1(run, case):
    run = Path(run)
    started = time.perf_counter()
    ms = generate(case, run / case)
    sol = library_solve(ms, {"type": "Sa", "solint": 8})
    truth = truth_of(ms)
    c = columns(ms, ["TIME", "ANTENNA1", "ANTENNA2", "MODEL_TRUE"], sol.rows)
    blocks = bin_blocks(sol.time_bin, c["TIME"], truth)
    gt = truth["gains"][blocks][:, :1]  # flat in frequency
    nant = gt.shape[2]
    sigma = float(truth["sigma_jy"])
    a1, a2, tb = c["ANTENNA1"], c["ANTENNA2"], sol.time_bin
    m2 = np.abs(c["MODEL_TRUE"][..., (0, 3)]) ** 2  # (row, chan, hand)
    a = np.zeros((len(blocks), nant, 2))
    for h in range(2):
        g2 = np.abs(gt[:, 0, :, h]) ** 2  # (bin, ant)
        s = m2[..., h].sum(1)
        np.add.at(a[..., h], (tb, a1), s * g2[tb, a2])
        np.add.at(a[..., h], (tb, a2), s * g2[tb, a1])
    p, q = np.triu_indices(nant, 1)
    g2 = np.abs(gt[:, 0]) ** 2  # (bin, ant, hand)
    s_pq = sigma * np.sqrt(g2[:, q] / a[:, p] + g2[:, p] / a[:, q])  # (bin, pair, hand)
    prod, ok, _ = cal_gain.baseline_products(sol.gains, sol.flags)
    pt, _, _ = cal_gain.baseline_products(gt, np.zeros(gt.shape, bool))
    r = (np.abs(prod - pt)[:, 0] / s_pq)[ok[:, 0]]
    res = {
        "case": case,
        "products": int(ok.sum()),
        "r_median": float(np.median(r)),
        "r_p95": float(np.percentile(r, 95)),
        "s_pq_median": float(np.median(s_pq)),
        "s_pq_phase_deg_median": float(np.degrees(np.median(s_pq / np.abs(pt[:, 0])))),
        "wall_s": time.perf_counter() - started,
    }
    res["pass"] = bool(res["r_median"] <= T1["median"] and res["r_p95"] <= T1["p95"])
    write(run / f"t1-{case}.json", res)
    return res["pass"]


# --- the loop -------------------------------------------------------------------


def loop_paths(run, case, loop):
    d = Path(run) / f"{loop}-{case}"
    return d, d / f"{case}.ms", d / "run"


def image_of(loop):
    if loop.endswith("-fine"):
        return IMAGE_FINE
    if loop == "pashallow":
        return IMAGE.replace("auto_threshold: 3.0", "auto_threshold: 10.0")
    return IMAGE


def config_text(loop):
    return (
        "schema: rang-config\nversion: 1\nfields: {target: [SIM-TARGET]}\n"
        f"image: {image_of(loop)}\nselfcal:\n"
        f"  rounds: {ROUNDS.get(loop, 2)}\n  terms: {LOOPS[loop.removesuffix('-fine')]}\n"
        "  input_column: DATA\n  refant: 0\nrun: {stages: [selfcal]}\n"
    )


def loop(run, case, loop_name):
    d, ms, run_dir = loop_paths(run, case, loop_name)
    d.mkdir(parents=True, exist_ok=True)
    generate(case, d)
    config = d / "config.yaml"
    config.write_text(config_text(loop_name), encoding="utf-8")
    summary_path = run_dir / "selfcal" / "summary.json"
    timing = {}
    if not summary_path.is_file():
        env = dict(os.environ)
        env["PATH"] = f"{ROOT / 'core/target/release'}:{env['PATH']}"
        started = time.perf_counter()
        argv = ["flock", str(LOCK), str(Path(sys.executable).parent / "rang-core"),
                "selfcal", str(config), str(ms), "--run-dir", str(run_dir)]  # fmt: skip
        with (d / "stage.log").open("w") as log:
            subprocess.run(["/usr/bin/time", "-v", *argv], stdout=log,
                           stderr=subprocess.STDOUT, check=True, env=env)  # fmt: skip
        timing["stage_wall_s_with_lock_wait"] = time.perf_counter() - started
    summary = json.loads(summary_path.read_text())
    (field,) = summary["fields"]
    res = {"case": case, "loop": loop_name, "rounds": [], **timing}
    ok = True
    meta = columns(ms, ["FIELD_ID", "TIME", "SCAN_NUMBER"])
    rows = np.flatnonzero(meta["FIELD_ID"] == 3)
    freq = np.asarray(columns(ms / "SPECTRAL_WINDOW", ["CHAN_FREQ"])["CHAN_FREQ"][0])
    for r in field["rounds"]:
        k, term = r["round"], r["term"]
        _gains, _gflags, gtime, gfreq, gscan = cal_selfcal.read_store(
            r["store"], term["name"]
        )
        sol = solution_from_store(r, term, rows, meta, freq)
        entry = {
            "round": k,
            "term": term,
            "solve": r["solve"],
            "image_wall_s": r["image"]["wall_seconds"],
            "apply": r["apply"],
        }
        g4 = intervals(term, meta, rows, freq, gtime, gfreq, gscan)
        entry["g4_bins"] = g4
        ok &= g4["pass"]
        got = against_truth(ms, sol)
        entry["truth"] = got
        gates = T2.get((loop_name.removesuffix("-fine"), k))
        if gates and got is not None:
            entry["t2"] = t2_gates(gates, got)
            ok &= entry["t2"]["pass"]
        res["rounds"].append(entry)
    final = field["rounds"][-1]
    res["g4_apply"] = final_apply(ms, final, rows, meta, freq)
    ok &= res["g4_apply"]["pass"]
    res["final_image_wall_s"] = field["final_image"]["wall_seconds"]
    res["pass"] = bool(ok)
    write(Path(run) / f"loop-{loop_name}-{case}.json", res)
    return ok


def expected_bins(solint, meta, rows):
    """The frozen rule of G4, written apart from rang.cal_selfcal: per scan
    N integrations from its start ('inf' all, 'int' 1), or CASA's bins for
    seconds; returns (bin per row, gain_time, scan per bin)."""
    t, s = meta["TIME"][rows], meta["SCAN_NUMBER"][rows]
    if isinstance(solint, str) and solint.endswith("s"):
        tb, _ = cal_gain.solint_bins(t, s, meta["FIELD_ID"][rows], solint, "")
        tb = np.asarray(tb)
        firsts = [t[tb == b].min() for b in range(tb.max() + 1)]
        order = np.argsort(firsts)
        rank = np.empty_like(order)
        rank[order] = np.arange(len(order))
        tb = rank[tb]
    else:
        tb = np.empty(len(rows), np.int64)
        base = 0
        for scan in sorted(np.unique(s), key=lambda x: t[s == x].min()):
            sel = s == scan
            u = np.unique(t[sel])
            n = len(u) if solint == "inf" else (1 if solint == "int" else int(solint))
            tb[sel] = base + np.searchsorted(u, t[sel]) // n
            base = tb[sel].max() + 1
    gt = np.array([np.unique(t[tb == b]).mean() for b in range(tb.max() + 1)])
    gs = np.array([s[tb == b][0] for b in range(tb.max() + 1)])
    return tb, gt, gs


def intervals(term, meta, rows, freq, gtime, gfreq, gscan):
    _tb, gt, gs = expected_bins(term["solint"], meta, rows)
    if term["type"] == "Sd":
        fexp = freq
    else:
        fi = term.get("freqint", "inf")
        step = len(freq) if fi == "inf" else int(fi)
        fexp = np.array([freq[i : i + step].mean() for i in range(0, len(freq), step)])
    per_scan = {int(x): int((gs == x).sum()) for x in np.unique(gs)}
    out = {
        "time_bins": len(gtime),
        "expected_time_bins": len(gt),
        "per_scan": per_scan,
        "freq_bins": len(gfreq),
        "expected_freq_bins": len(fexp),
    }
    same_t = len(gt) == len(gtime) and np.max(np.abs(gt - gtime)) <= 1e-6
    same_s = np.array_equal(gs, gscan)
    same_f = len(fexp) == len(gfreq) and np.allclose(fexp, gfreq, rtol=0, atol=1e-3)
    out["pass"] = bool(same_t and same_s and same_f)
    return out


def solution_from_store(r, term, rows, meta, freq):
    gains, gflags, gtime, gfreq, gscan = cal_selfcal.read_store(
        r["store"], term["name"]
    )
    tb, _, _ = expected_bins(term["solint"], meta, rows)
    if term["type"] == "Sd":
        fb = np.arange(len(freq))
        npz = np.load(r["store"] + ".delays.npz")
        delays = npz["delays_ns"]
    else:
        fi = term.get("freqint", "inf")
        step = len(freq) if fi == "inf" else int(fi)
        fb = np.arange(len(freq)) // step
        delays = None
    flags = np.repeat(gflags[..., None], 2, -1)
    return cal_selfcal.SelfcalSolution(
        name=term["name"], type=term["type"], gains=gains, flags=flags, rows=rows,
        time_bin=tb, freq_bin=fb, bin_scan=gscan, gain_time=gtime, gain_freq=gfreq,
        field_id=3, iterations=0, converged_fraction=0.0, clipped=0, delays=delays,
        offsets=None,
    )  # fmt: skip


def t2_gates(gates, got):
    p = got["products"]
    checks = {}
    for key, lim in gates.items():
        if key == "phase_deg":
            checks[key] = (
                p["phase_deg"]["median"] <= lim[0] and p["phase_deg"]["p95"] <= lim[1]
            )
        elif key == "amp_rel":
            checks[key] = (
                p["amp_rel"]["median"] <= lim[0] and p["amp_rel"]["p95"] <= lim[1]
            )
        elif key == "amp_vs_input":
            checks[key] = (
                p["amp_rel"]["median"] <= lim * p["uncorrected_amp_rel"]["median"]
            )
        elif key == "delay_ns":
            dl = got["delays"]
            checks[key] = dl["median"] <= lim[0] and dl["p95"] <= lim[1]
    return {
        "checks": {k: bool(v) for k, v in checks.items()},
        "pass": all(checks.values()),
    }


def final_apply(ms, final, rows, meta, freq):
    """G4: the output column against S_p^-1 V S_q^-H from the stored gains."""
    term = final["term"]
    sol = solution_from_store(final, term, rows, meta, freq)
    c = columns(ms, ["DATA", "CORRECTED_DATA", "FLAG", "ANTENNA1", "ANTENNA2"], rows)
    g = sol.gains[sol.time_bin][:, sol.freq_bin]  # (row, chan, ant, 2)
    idx = np.arange(len(rows))
    gp = g[idx, :, c["ANTENNA1"]]
    gq = np.conj(g[idx, :, c["ANTENNA2"]])
    hands = [(0, 0), (0, 1), (1, 0), (1, 1)]
    want = np.empty(c["DATA"].shape, complex)
    for k, (i, j) in enumerate(hands):
        want[..., k] = c["DATA"][..., k] / (gp[..., i] * gq[..., j])
    got = c["CORRECTED_DATA"]
    keep = np.abs(want) > 0
    rel = (np.abs(got - want) / np.abs(want))[keep]
    invalid = sol.flags.any(-1)[sol.time_bin][:, sol.freq_bin]
    expect_flag = invalid[idx, :, c["ANTENNA1"]] | invalid[idx, :, c["ANTENNA2"]]
    flag_ok = bool(np.array_equal(c["FLAG"].any(-1), expect_flag))
    out = {
        "cells": int(keep.sum()),
        "median": float(np.median(rel)),
        "max": float(rel.max()),
        "flags_as_expected": flag_ok,
    }
    out["pass"] = bool(
        out["median"] <= G4_APPLY["median"]
        and out["max"] <= G4_APPLY["max"]
        and flag_ok
    )
    return out


