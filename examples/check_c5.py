def qc(run, case, loop_name):
    d, ms, run_dir = loop_paths(run, case, loop_name)
    summary = json.loads((run_dir / "selfcal" / "summary.json").read_text())
    (field,) = summary["fields"]
    qdir = d / "qc"
    qdir.mkdir(exist_ok=True)
    meta = columns(ms, ["FIELD_ID", "TIME", "SCAN_NUMBER"])
    rows = np.flatnonzero(meta["FIELD_ID"] == 3)
    res = {"case": case, "loop": loop_name, "rounds": []}
    steps, cases = [], []
    started = time.perf_counter()
    for r in field["rounds"]:
        if r["apply"]["cells_flagged_after"] != r["apply"]["cells_flagged_before"]:
            raise SystemExit("a round flagged data; its successors' FLAG differs")
        k, term = r["round"], r["term"]
        copy = qdir / f"round-{k}.ms"
        if not copy.exists():
            shutil.copytree(ms, copy)
            prefix = Path(r["store"]).parent / "image"
            core_model.write_model_data(copy, prefix, 3, stage="c5-qc")
        # Precondition: rang's re-solve on the copy equals the stored gains.
        again = cal_selfcal.solve(
            copy, {**term}, rows=rows, field_id=3, input_column="DATA",
            model_column="MODEL_DATA", weight_column="WEIGHT_SPECTRUM", refant=0,
            gain_clip=(0.5, 2.0),
        )  # fmt: skip
        stored, _sflags, *_ = cal_selfcal.read_store(r["store"], term["name"])
        same = bool(np.array_equal(again.gains, stored))
        n = (
            0
            if term["solint"] == "inf"
            else (1 if term["solint"] == "int" else term["solint"])
        )
        if isinstance(n, str):
            n = None  # seconds: QuartiCal has no CASA bins
        fi = term.get("freqint", "inf")
        fint = 0 if term["type"] == "Sd" or fi == "inf" else int(fi)
        cases.append((k, term, again, same, n))
        if n is None:
            continue
        opts = [*QC_OPTIONS, f"G.type={cal_selfcal.QUARTICAL[term['type']]}",
                f"G.time_interval={n}", f"G.freq_interval={fint}"]  # fmt: skip
        out = qdir / f"qc-round-{k}"
        if not (out / "summary.json").is_file():
            steps.append(
                f"{QC} -I /ex/oracle_gain.py qc-solve /run/round-{k}.ms /run/qc-round-{k} "
                + " ".join(opts)
            )
    if steps:
        cf.TIMINGS.clear()
        with open(LOCK, "w") as lock:
            import fcntl

            fcntl.flock(lock, fcntl.LOCK_EX)
            cf.docker(cf.FORMATS_IMAGE, ["sh", "-c", " && ".join(steps)],
                      [(qdir, "/run", "rw"), (HERE, "/ex", "ro")],
                      f"quartical x{len(steps)}", env={"NUMBA_CACHE_DIR": "/run/numba"})  # fmt: skip
        res["timings"] = list(cf.TIMINGS)
    ok = True
    for k, term, again, same, n in cases:
        entry = {"round": k, "term": term, "resolve_equals_stage": same}
        ok &= same
        if n is not None:
            entry.update(qc_compare(qdir / f"qc-round-{k}", term, again))
            ok &= entry["pass"]
        else:
            entry["quartical"] = "not run: seconds bins are CASA's, QuartiCal has none"
        res["rounds"].append(entry)
    res["wall_s"] = time.perf_counter() - started
    res["pass"] = bool(ok)
    write(Path(run) / f"qc-{loop_name}-{case}.json", res)
    return ok


def qc_compare(out, term, sol):
    summary = json.loads((out / "summary.json").read_text())
    qg = np.load(out / "gains.npy")
    qg = np.stack([qg[..., 0], qg[..., 3]], -1)
    qf = np.repeat((np.load(out / "gain_flags.npy") != 0)[..., None], 2, -1)
    p1, ok1, _ = cal_gain.baseline_products(sol.gains, sol.flags)
    p2, ok2, _ = cal_gain.baseline_products(qg, qf)
    ok = ok1 & ok2
    rel = (np.abs(p1 - p2) / np.abs(p2))[ok]
    res = {
        "shape_rang": list(sol.gains.shape),
        "shape_qc": list(qg.shape),
        "products": int(ok.sum()),
        "median": float(np.median(rel)),
        "p95": float(np.percentile(rel, 95)),
        "max": float(rel.max()),
        "qc_gain_times_equal": bool(
            len(summary["gain_times"]) == len(sol.gain_time)
            and np.max(np.abs(np.array(summary["gain_times"]) - sol.gain_time)) <= 1e-6
        ),
        "qc_chunk_gain_times": summary["chunk_gain_times"],
        "qc_wall_s": summary.get("time_wall"),
        "conv_iter": summary.get("conv_iter"),
    }
    passed = res["median"] <= QC_B["median"] and res["p95"] <= QC_B["p95"]
    passed &= res["qc_gain_times_equal"]
    if term["type"] == "Sd":
        names = summary["param_names"]
        params = np.load(out / "params.npy")
        qd = params[..., [names.index("delay_XX"), names.index("delay_YY")]] * 1e9
        nant = qd.shape[2]
        p, q = np.triu_indices(nant, 1)
        dr = sol.delays[:, 0][:, p] - sol.delays[:, 0][:, q]
        dq = qd[:, 0][:, p] - qd[:, 0][:, q]
        good = ~sol.flags[:, 0][:, p] & ~sol.flags[:, 0][:, q]
        x = np.abs(dr - dq)[good]
        res["delay_median_ns"] = float(np.median(x))
        res["delay_p95_ns"] = float(np.percentile(x, 95))
        res["delay_max_ns"] = float(x.max())
        passed &= (
            res["delay_median_ns"] <= QC_B["delay_median_ns"]
            and res["delay_p95_ns"] <= QC_B["delay_p95_ns"]
        )
    res["pass"] = bool(passed)
    return res


