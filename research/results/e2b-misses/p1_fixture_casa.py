"""P1's fixture (research/e2b-misses.md 9.15): casacore's parallactic angle
at synthetic cases, in CASA 6.7.6.14's casatools; imports no `rang`.

    p1_fixture_casa.py OUT_JSON

K = me.posangle(source in AZEL, HADEC pole in AZEL), frame = UTC epoch and
the antenna's ITRF position, as MSDerivedValues::parAngle. Cases within 5
degrees of the zenith are left out (the angle is ill-conditioned there).
"""

import json
import sys

import numpy as np

ANTENNAS = {  # MeerKAT ITRF (m), from the E2-B MS's ANTENNA table
    "m000": (5109271.497354, 2006808.893028, -3239130.736141),
    "m021": (5109319.275022, 2006518.560600, -3239233.619577),
    "m033": (5109561.411240, 2007555.508268, -3238207.174221),
}
EPOCHS = ("2019-03-01T03:00:00", "2021-02-10T09:20:00", "2022-11-05T21:30:00",
          "2024-06-20T12:00:00")  # fmt: skip
HOURS = (0.0, 2.5, 5.0)
DIRECTIONS_DEG = [(ra, dec) for ra, dec in zip(np.linspace(5, 355, 12),
                  (-85, -70, -60, -50, -40, -30, -20, -10, 0, 10, 25, 40))]  # fmt: skip


def main(out):
    from casatools import measures, quanta

    me, qa = measures(), quanta()

    def rad(q):
        return qa.convert(q, "rad")["value"]

    pole = me.direction("HADEC", "0rad", qa.quantity(np.pi / 2, "rad"))
    cases = []
    for name, xyz in ANTENNAS.items():
        pos = me.position("ITRF", *(qa.quantity(v, "m") for v in xyz))
        me.doframe(pos)
        for iso in EPOCHS:
            t0 = qa.convert(qa.quantity(iso), "s")["value"]
            for hr in HOURS:
                t = t0 + 3600.0 * hr
                me.doframe(me.epoch("utc", qa.quantity(t, "s")))
                for ra, dec in DIRECTIONS_DEG:
                    src = me.direction("J2000", qa.quantity(ra, "deg"), qa.quantity(dec, "deg"))
                    s_az = me.measure(src, "AZEL")
                    if rad(s_az["m1"]) > np.radians(85):
                        continue
                    k = rad(me.posangle(s_az, me.measure(pole, "AZEL")))
                    cases.append({"antenna": name, "itrf_m": list(xyz), "time_mjd_s": t,
                                  "ra_rad": float(np.radians(ra)), "dec_rad": float(np.radians(dec)),
                                  "elevation_rad": rad(s_az["m1"]), "casacore_pa_rad": k})  # fmt: skip
    doc = {
        "about": "casacore's parallactic angle (me.posangle in AZEL, CASA 6.7.6.14 casatools), "
                 "research/e2b-misses.md 9.15; generated by "
                 "research/results/e2b-misses/p1_fixture_casa.py",
        "cases": cases,
    }  # fmt: skip
    with open(out, "w") as f:
        json.dump(doc, f, indent=0)
        f.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
